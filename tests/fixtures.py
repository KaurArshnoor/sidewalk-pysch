import numpy as np
import pandas as pd

from data import digest


def generate(output: Path):
    output.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(42)
    rows = []
    for m in range(20):
        metro_effect = rng.normal(0, 1.8)
        for t in range(16):
            # Plausibly shaped strings ONLY; not actual census assignments.
            geoid = f"99{m:03d}{t:06d}"
            poverty = rng.uniform(3, 35)
            income = rng.uniform(30000, 130000)
            walk = rng.uniform(2, 19)
            parks = rng.uniform(10, 95)
            row = {"geoid": geoid, "metro": f"TEST-{m + 1:02d}", "walkability": walk,
                   "population": int(rng.integers(1000, 7000)), "poverty_pct": poverty, "income": income,
                   "age65_pct": rng.uniform(5, 30), "black_pct": rng.uniform(0, 60),
                   "hispanic_pct": rng.uniform(0, 60), "pop_density": rng.uniform(200, 12000),
                   "park_access_pct": parks, "amenities_per_1000": rng.uniform(0.2, 8),
                   "distress_pct": 18 - 0.24 * walk + 0.10 * poverty - income / 100000 + metro_effect + rng.normal(0, 0.7)}
            rows.append(row)
    pd.DataFrame(rows).to_csv(output / "tracts.csv", index=False)
    source_id = "synthetic-fixture-seed42"
    manifest = {
        "snapshot": "synthetic-v1-seed42", "synthetic": True, "geography_id": "invented-tracts",
        "files": {p.name: digest(p) for p in [output / "tracts.csv"]},
        "sources": [{"id": source_id, "title": "Invented test fixture, seed 42; NOT CDC/EPA/ACS data",
                     "url": "fixture://tests/fixtures.py", "release": "synthetic v1",
                     "geography": "invented-tracts", "retrieved_at": "2026-11-08T00:00:00Z",
                     "sha256": digest(output / "tracts.csv"), "notes": ["Generated by tests/fixtures.py."]}],
        "column_sources": {c: [source_id] for c in rows[0] if c not in {"geoid", "metro"}},
        "definitions": {"distress_pct": "Invented mental distress percentages, not measured loneliness.",
                        "walkability": "Invented index on a 1–20 scale."},
        "scope": {"description": "320 invented tracts in 20 invented metros", "top20_verified": False},
        "caveats": ["This fixture deliberately encodes a negative association for testing."]}
